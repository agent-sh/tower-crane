'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { readText, escapeTableCell } = require('./text');

const ROOT = path.join(__dirname, '..');
const TABLES = ['Plan', 'Stack', 'Run', 'Decisions', 'Views', 'Agents and worktrees', 'Gates'];

function generate(root = ROOT) {
  const { COMMANDS, generalHelp, commandHelp, groupHelp } = require(path.join(root, 'bin', 'tower-crane.js'));
  for (const file of fs.readdirSync(path.join(root, 'lib')).filter((name) => /^commands-(?!specs\.js$).*\.js$/.test(name))) {
    const source = readText(path.join(root, 'lib', file));
    const body = source.match(/const COMMANDS = \[\n([\s\S]*?)\n\];/);
    if (!body) throw new Error(`${file}: COMMANDS table is missing`);
    const lines = body[1].split('\n').filter((line) => line.trim());
    if (lines.some((line) => !/^  \{ section: .* \},$/.test(line))) {
      throw new Error(`${file}: COMMANDS must have one entry per line, separated by blank lines`);
    }
    if (body[1] !== lines.join('\n\n')) throw new Error(`${file}: separate COMMANDS entries with one blank line`);
    const names = lines.map((line) => line.match(/name: '([^']+)'/)[1]);
    if (names.join('\n') !== [...names].sort().join('\n')) throw new Error(`${file}: COMMANDS must be sorted by name`);
  }
  const names = COMMANDS.map((c) => c.name);
  if (new Set(names).size !== names.length || names.join('\n') !== [...names].sort().join('\n')) {
    throw new Error('COMMANDS must be sorted by name with no duplicates');
  }
  if (COMMANDS.some((c) => !TABLES.includes(c.section) || !c.summary
    || (c.description !== undefined && (typeof c.description !== 'string' || !c.description.trim()))
    || /[\r\n]/.test(c.summary + (c.usage || '') + (c.description || '')))) {
    throw new Error('every command needs a known section and single-line usage, summary and description');
  }
  const docPath = path.join(root, 'docs', 'cli.md');
  const original = readText(docPath);
  const template = readText(path.join(root, 'scripts', 'cli-reference.md'));
  let generated = template;
  for (const section of TABLES) {
    const start = `<!-- commands:${section}:start -->`;
    const end = `<!-- commands:${section}:end -->`;
    if (template.split(start).length !== 2 || template.split(end).length !== 2) {
      throw new Error(`scripts/cli-reference.md needs exactly one ${section} command block`);
    }
    const from = generated.indexOf(start) + start.length;
    const to = generated.indexOf(end);
    if (to < from) throw new Error(`invalid ${section} command block`);
    const commands = COMMANDS.filter((c) => section === 'Stack' ? c.name.startsWith('stack ')
      : c.section === section && !c.name.startsWith('stack '));
    const rows = commands.map((c) => `| \`${escapeTableCell(c.name + (c.usage ? ` ${c.usage}` : ''))}\` | ${escapeTableCell(c.description || c.summary)} |`);
    // Empty table rows separate edits without breaking the Markdown table.
    generated = generated.slice(0, from) + '\n| Command | Does |\n|---|---|\n' + rows.join('\n| | |\n') + '\n' + generated.slice(to);
  }
  const fence = (text) => {
    const runs = [...text.matchAll(/`+/g)].map((match) => match[0].length);
    const ticks = '`'.repeat(Math.max(3, ...runs.map((length) => length + 1)));
    return `${ticks}text\n${text}\n${ticks}`;
  };
  const help = (label, text) => `<details>\n<summary>${label}</summary>\n\n${fence(text)}\n\n</details>`;
  const groups = [...new Set(COMMANDS.filter((c) => c.name.includes(' ')).map((c) => c.name.split(' ')[0]))];
  generated = '<!-- Generated by npm run docs:cli from CLI help and scripts/cli-reference.md. Do not edit this file by hand. -->\n\n'
    + generated.trimEnd() + '\n\n## Command help\n\n'
    + [help('tower-crane --help', generalHelp()),
      ...groups.map((group) => help(`tower-crane ${group} --help`, groupHelp(group))),
      ...COMMANDS.map((command) => help(`tower-crane ${command.name} --help`, commandHelp(command)))].join('\n\n') + '\n';
  return { docPath, original, generated };
}

function check(root = ROOT) {
  const { original, generated } = generate(root);
  if (original !== generated) throw new Error('docs/cli.md command rows drifted or help/prose changed; run npm run docs:cli');
}

if (require.main === module) {
  try {
    if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('usage: node scripts/cli-docs.js [--check]');
    if (process.argv.includes('--check')) check();
    else {
      const { docPath, generated } = generate();
      fs.writeFileSync(docPath, generated);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { generate, check };
